_cache: tuple[str, str, str] | None = None


def materialize() -> tuple[str, str, str]:
    """Write the CA, client certificate and key to a private temp dir.

    Returns ``(ca_path, cert_path, key_path)``. The files are created once per
    process with 0600 permissions.
    """
    global _cache
    if _cache is not None:
        return _cache

    directory = tempfile.mkdtemp(prefix="magicscoop-certs-")
    paths = []
    for filename, blob in (
        ("ca.pem", CA_PEM_B64),
        ("client.pem", CLIENT_CERT_B64),
        ("client.key", CLIENT_KEY_B64),
    ):
        path = os.path.join(directory, filename)
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "wb") as handle:
            handle.write(base64.b64decode("".join(blob.split())))
        paths.append(path)

    _cache = (paths[0], paths[1], paths[2])
    return _cache
